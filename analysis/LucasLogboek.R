  # Slaap en hartslag — logboek
  
  ## Introductie
  
  Slaap is belangrijk voor het herstel van zowel het lichaam als de hersenen. 
Tijdens het slapen daalt de hartslag meestal, omdat het lichaam ontspant en energie herstelt. 
Een lagere hartslag tijdens de slaap wordt daarom vaak gekoppeld aan een betere slaapkwaliteit. 
Factoren zoals stress, beweging, voeding en schermgebruik in de avond kunnen invloed hebben op zowel slaap als hartslag.

In dit onderzoek bekijken we of een betere slaapkwaliteit samenhangt met een lagere gemiddelde hartslag. 
Drie proefpersonen dragen vier weken lang een Fitbit-smartwatch die continu slaap en hartslag meet. 
Daarnaast vullen zij elke dag een korte vragenlijst in over onder andere beweging, alcoholgebruik, eetgewoonten en schermtijd voor het slapen gaan.


- Gebruikte data: De ge-exporteerde fitbit data met de output in `analysis/data/combined_data_robin.csv, analysis/data/combined_data_mohammed.csv, analysis/data/combined_data_lucas.csv
- Duur van het onderzoek: Over een verloop van vier weken met drie proefpersonen
